create table if not exists public.direct_call_sessions (
  call_id uuid primary key,
  caller_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  caller_name text not null,
  offer jsonb not null,
  status text not null default 'ringing' check (status in ('ringing', 'accepted', 'declined', 'ended', 'missed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint direct_call_distinct_participants check (caller_id <> recipient_id)
);

alter table public.direct_call_sessions drop constraint if exists direct_call_sessions_status_check;
alter table public.direct_call_sessions add constraint direct_call_sessions_status_check
  check (status in ('ringing', 'accepted', 'declined', 'ended', 'missed'));

create index if not exists direct_call_sessions_inbox_idx
  on public.direct_call_sessions (recipient_id, created_at desc)
  where status = 'ringing';

alter table public.direct_call_sessions enable row level security;
revoke update on public.direct_call_sessions from anon, authenticated;
grant update (status, updated_at) on public.direct_call_sessions to authenticated;

drop policy if exists "Call participants can read their call sessions" on public.direct_call_sessions;
create policy "Call participants can read their call sessions"
on public.direct_call_sessions for select to authenticated
using (auth.uid() = caller_id or auth.uid() = recipient_id);

drop policy if exists "Callers can create direct call sessions" on public.direct_call_sessions;
create policy "Callers can create direct call sessions"
on public.direct_call_sessions for insert to authenticated
with check (
  auth.uid() = caller_id
  and exists (
    select 1 from public.direct_messages dm
    where (dm.sender_id = caller_id and dm.recipient_id = recipient_id)
       or (dm.sender_id = recipient_id and dm.recipient_id = caller_id)
  )
  and not exists (
    select 1 from public.blocked_users bu
    where (bu.blocker_id = caller_id and bu.blocked_id::text = recipient_id::text)
       or (bu.blocker_id = recipient_id and bu.blocked_id::text = caller_id::text)
  )
);

drop policy if exists "Call participants can update call sessions" on public.direct_call_sessions;
create policy "Call participants can update call sessions"
on public.direct_call_sessions for update to authenticated
using (auth.uid() = caller_id or auth.uid() = recipient_id)
with check (auth.uid() = caller_id or auth.uid() = recipient_id);

create table if not exists public.direct_call_ice_candidates (
  id bigint generated by default as identity primary key,
  call_id uuid not null references public.direct_call_sessions(call_id) on delete cascade,
  from_user_id uuid not null references auth.users(id) on delete cascade,
  to_user_id uuid not null references auth.users(id) on delete cascade,
  candidate jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists direct_call_ice_candidates_inbox_idx
  on public.direct_call_ice_candidates (call_id, to_user_id, id);

alter table public.direct_call_ice_candidates enable row level security;

drop policy if exists "Call participants can read ICE candidates" on public.direct_call_ice_candidates;
create policy "Call participants can read ICE candidates"
on public.direct_call_ice_candidates for select to authenticated
using (
  exists (
    select 1 from public.direct_call_sessions s
    where s.call_id = direct_call_ice_candidates.call_id
      and (auth.uid() = s.caller_id or auth.uid() = s.recipient_id)
  )
);

drop policy if exists "Call participants can send ICE candidates" on public.direct_call_ice_candidates;
create policy "Call participants can send ICE candidates"
on public.direct_call_ice_candidates for insert to authenticated
with check (
  from_user_id = auth.uid()
  and exists (
    select 1 from public.direct_call_sessions s
    where s.call_id = direct_call_ice_candidates.call_id
      and ((s.caller_id = from_user_id and s.recipient_id = to_user_id)
        or (s.recipient_id = from_user_id and s.caller_id = to_user_id))
      and s.status in ('ringing', 'accepted')
  )
);

create table if not exists public.push_subscriptions (
  endpoint text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subscription jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists push_subscriptions_user_idx on public.push_subscriptions (user_id);
alter table public.push_subscriptions enable row level security;

drop policy if exists "Users manage their own push subscriptions" on public.push_subscriptions;
create policy "Users manage their own push subscriptions"
on public.push_subscriptions for all to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

