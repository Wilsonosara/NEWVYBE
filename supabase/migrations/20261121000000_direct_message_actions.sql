alter table public.direct_messages
  add column if not exists edited_at timestamptz,
  add column if not exists reply_to_id bigint references public.direct_messages(id) on delete set null;

drop policy if exists "Users can edit own direct messages" on public.direct_messages;
create policy "Users can edit own direct messages"
  on public.direct_messages for update to authenticated
  using (sender_id = auth.uid())
  with check (sender_id = auth.uid());

drop policy if exists "Users can delete own direct messages" on public.direct_messages;
create policy "Users can delete own direct messages"
  on public.direct_messages for delete to authenticated
  using (sender_id = auth.uid());

create table if not exists public.direct_message_reactions (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.direct_messages(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  emoji text not null check (char_length(emoji) between 1 and 16),
  created_at timestamptz not null default now(),
  unique (message_id, user_id, emoji)
);

alter table public.direct_message_reactions enable row level security;

drop policy if exists "Conversation members can view message reactions" on public.direct_message_reactions;
create policy "Conversation members can view message reactions"
  on public.direct_message_reactions for select to authenticated
  using (exists (
    select 1 from public.direct_messages dm
    where dm.id = message_id
      and auth.uid() in (dm.sender_id, dm.recipient_id)
  ));

drop policy if exists "Conversation members can add own message reactions" on public.direct_message_reactions;
create policy "Conversation members can add own message reactions"
  on public.direct_message_reactions for insert to authenticated
  with check (
    user_id = auth.uid()
    and exists (
      select 1 from public.direct_messages dm
      where dm.id = message_id
        and auth.uid() in (dm.sender_id, dm.recipient_id)
    )
  );

drop policy if exists "Users can remove own message reactions" on public.direct_message_reactions;
create policy "Users can remove own message reactions"
  on public.direct_message_reactions for delete to authenticated
  using (user_id = auth.uid());

grant select, insert, delete on public.direct_message_reactions to authenticated;
grant usage, select on sequence public.direct_message_reactions_id_seq to authenticated;
